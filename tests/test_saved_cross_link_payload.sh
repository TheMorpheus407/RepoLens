# Saved payloads are replaced only after complete reattestation; all I/O is mocked.
# shellcheck disable=SC2034,SC2329 # Callbacks consume fixture globals.
set -uo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source "$REPO/lib/filing.sh"
FIXTURE="$(mktemp -d)" || exit 1
trap 'rm -rf -- "$FIXTURE"' EXIT
case_payload() (
  action="$1" phase="$2"
  LOG_BASE="$FIXTURE/$action-$phase"
  cross_dir="$LOG_BASE/final/filed/cross-link"
  key="$action-9"
  mkdir -p "$cross_dir"
  FORGE_REPO=acme/repo CROSS_LINK_MODE=suggest-reopen
  REPOLENS_FINAL_STATE=finished parent_pid="$BASHPID"
  trap 'REPOLENS_FINAL_STATE=interrupted' HUP INT TERM
  : > "$cross_dir/$key.done"
  printf 'https://example.invalid/saved-response\n' > "$cross_dir/$key.created-response"
  printf 'saved exact body\n\n' > "$cross_dir/$key.body.md"
  printf 'saved exact banner\n\n' > "$cross_dir/$key.body.banner.md"
  command jq -n --arg type "$action" '[{cluster_id:"c1",body:"evidence",cross_link_actions:[
    {type:$type,issue_number:9,body:"candidate body\n\n"}]}]' > "$LOG_BASE/final/manifest.json"
  filing_verify_cluster_citations() { return 0; }
  branch_scope_verify_body() { return 0; }
  repolens_extract_citations() { return 0; }
  _filing_action_reference_candidates() { return 0; }
  forge_filing_capable() { return 0; }
  forge_issue_number_from_url() { printf '17\n'; }
  forge_issue_comment_once() { printf 'POST\n' >> "$LOG_BASE/posts"; return 99; }
  forge_issue_create_once() { forge_issue_comment_once "$@"; }
  candidate_body=''
  jq() {
    if [[ "$1" == -jr && "$phase" == body-failure ]]; then
      printf 'partial'
      kill -TERM "$parent_pid"
      return 1
    fi
    command jq "$@" || return 1
    if [[ "$1" == -jr && "$phase" == body-success ]]; then kill -TERM "$parent_pid"; fi
  }
  # The actual candidate path is passed to the adapter only for new POSTs;
  # saved readbacks instead contain the expected exact regenerated payload.
  readback() {
    if [[ "$phase" == readback-* ]]; then
      kill -TERM "$parent_pid"
      [[ "$phase" != readback-failure ]] || return 1
    fi
    if [[ "$phase" == invalid ]]; then printf '{}\n'; return; fi
    if [[ "$action" == comment ]]; then
      command jq -cn '{url:"https://example.invalid/saved-response",body:"candidate body\n\n"}'
    else
      # shellcheck disable=SC2016 # Literal Markdown backticks.
      printf -v candidate_body '> Generated by RepoLens run probe\n> Source: closed issue #9\n\ncandidate body\n\n\n\nLabel suggestion: %s\n' '`repolens:reopen-candidate`'
      command jq -cn --arg body "$candidate_body" '{url:"https://example.invalid/saved-response",title:"[reopen-candidate] consider re-opening #9",body:$body,state:"open"}'
    fi
  }
  forge_issue_comment_read_json() { readback; }
  forge_issue_read_json() {
    if [[ "$2" != 9 ]]; then readback
    elif [[ "$action" == comment ]]; then printf '{"state":"open"}\n'
    else printf '{"state":"closed"}\n'; fi
  }
  # Inject failures/signals after actual promotion, while originals must remain recoverable.
  eval "$(declare -f _branch_scope_replace_file | sed '1s/_branch_scope_replace_file/original_replace_file/')"
  _branch_scope_replace_file() {
    local source="$1" target="$2"
    if [[ "$source" == *.reconcile.* && "$source" != */originals/* ]]; then
      if [[ ( "$phase" == promote-body-failure || "$phase" == absent-body-failure ) && "$target" == "$cross_dir/$key.body.md" ]]; then return 1; fi
      original_replace_file "$@" || return 1
      if [[ "$phase" == promote-banner-* && "$target" == "$cross_dir/$key.body.banner.md" ]]; then
        kill -s "${phase##*-}" "$parent_pid"
      elif [[ ( "$phase" == promote-body-* || "$phase" == absent-body-TERM ) && "$phase" != promote-body-failure && "$target" == "$cross_dir/$key.body.md" ]]; then
        kill -s "${phase##*-}" "$parent_pid"
      fi
    else
      original_replace_file "$@"
    fi
  }
  if [[ "$phase" == absent-* ]]; then rm -f "$cross_dir/$key.body.md"; fi
  cp() {
    if [[ "$phase" == backup-failure ]]; then return 1; fi
    command cp "$@"
  }
  rc=0
  _filing_cross_link_enact probe || rc=$?
  [[ ! -e "$LOG_BASE/posts" ]] || exit 1
  [[ "$(command cat "$cross_dir/$key.created-response")" == https://example.invalid/saved-response ]] || exit 1
  if [[ "$phase" == control ]]; then
    [[ "$rc" == 0 && -e "$cross_dir/$key.done" ]] || exit 1
    cmp -s <(printf 'candidate body\n\n') "$cross_dir/$key.body.md" || exit 1
    if [[ "$action" == reopen-suggestion ]]; then
      # Pin every byte, including trailing newlines, independently of readback().
      # shellcheck disable=SC2016 # Literal Markdown backticks.
      cmp -s <(printf '> Generated by RepoLens run probe\n> Source: closed issue #9\n\ncandidate body\n\n\n\nLabel suggestion: `repolens:reopen-candidate`\n') "$cross_dir/$key.body.banner.md" || exit 1
    fi
  else
    if [[ "$phase" == absent-* ]]; then
      [[ ! -e "$cross_dir/$key.body.md" ]] || exit 1
    else
      cmp -s <(printf 'saved exact body\n\n') "$cross_dir/$key.body.md" || exit 1
    fi
    cmp -s <(printf 'saved exact banner\n\n') "$cross_dir/$key.body.banner.md" || exit 1
    if [[ "$phase" == invalid || "$phase" == promote-body-failure || "$phase" == absent-body-failure || "$phase" == backup-failure ]]; then
      [[ "$rc" == 0 && ! -e "$cross_dir/$key.done" && -e "$cross_dir/$key.unverified-done" && -e "$cross_dir/$key.failed" ]] || exit 1
    else
      [[ "$rc" == 1 && -e "$cross_dir/$key.done" && ! -e "$cross_dir/$key.unverified-done" && ! -e "$cross_dir/$key.failed" ]] || exit 1
    fi
  fi
  # Temporary candidates must be cleaned on both success and failure.
  shopt -s nullglob
  candidates=("$cross_dir/"*.reconcile.*)
  (( ${#candidates[@]} == 0 ))
)
failed=0
for action in comment reopen-suggestion; do
  for phase in body-success body-failure readback-success readback-failure control invalid promote-body-failure promote-body-HUP promote-body-INT promote-body-TERM promote-banner-HUP promote-banner-INT promote-banner-TERM absent-body-failure absent-body-TERM backup-failure; do
    [[ "$action" != comment || "$phase" != promote-banner-* ]] || continue
    if case_payload "$action" "$phase"; then printf 'PASS: %s/%s\n' "$action" "$phase"
    else printf 'FAIL: %s/%s\n' "$action" "$phase"; failed=$((failed+1)); fi
  done
done
(( failed == 0 ))
