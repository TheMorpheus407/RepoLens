# Invalid saved payload paths must not receive nested private candidates.
# shellcheck disable=SC2034,SC2329 # Fixture callbacks consume these globals.
set -uo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=/dev/null
source "$REPO/lib/filing.sh"
fixture="$(mktemp -d)" || exit 1
trap 'rm -rf -- "$fixture"' EXIT
case_payload() (
  action="$1" kind="$2"
  LOG_BASE="$fixture/$action-$kind" FORGE_REPO=acme/repo CROSS_LINK_MODE=suggest-reopen
  REPOLENS_FINAL_STATE=finished
  prefix="$LOG_BASE/final/filed/cross-link/$action-9"
  outside="$LOG_BASE/unrelated-directory"
  mkdir -p "${prefix%/*}" "$outside"
  : > "$prefix.done"
  printf 'https://example.invalid/saved-response\n' > "$prefix.created-response"
  printf 'saved body\n' > "$prefix.body.md"
  printf 'saved banner\n' > "$prefix.body.banner.md"
  target="$prefix.body.md"
  [[ "$action" != reopen-suggestion ]] || target="$prefix.body.banner.md"
  rm "$target"
  if [[ "$kind" == directory ]]; then mkdir "$target"; else ln -s "$outside" "$target"; fi
  jq -n --arg action "$action" '[{cluster_id:"c1",body:"parent evidence",cross_link_actions:[{type:$action,issue_number:9,body:"candidate body\n"}]}]' > "$LOG_BASE/final/manifest.json"
  # Citations are irrelevant to this publication boundary. Mock only validation
  # and forge reads, while real regeneration, snapshots and receipt logic run.
  filing_verify_cluster_citations() { return 0; }
  branch_scope_verify_body() { return 0; }
  repolens_extract_citations() { return 0; }
  _filing_action_reference_candidates() { return 0; }
  forge_filing_capable() { return 0; }
  forge_issue_number_from_url() { printf '17\n'; }
  forge_issue_create_once() { printf 'UNEXPECTED POST\n' >> "$LOG_BASE/posts"; return 99; }
  forge_issue_comment_once() { forge_issue_create_once "$@"; }
  forge_issue_comment_read_json() {
    jq -cn '{url:"https://example.invalid/saved-response",body:"candidate body\n"}'
  }
  forge_issue_read_json() {
    if [[ "$2" == 9 ]]; then
      if [[ "$action" == comment ]]; then printf '{"state":"open"}\n'; else printf '{"state":"closed"}\n'; fi
    else
      # shellcheck disable=SC2016 # The Markdown label is literal fixture data.
      printf -v expected_banner '> Generated by RepoLens run probe\n> Source: closed issue #9\n\ncandidate body\n\n\nLabel suggestion: `repolens:reopen-candidate`\n'
      jq -cn --arg body "$expected_banner" '{url:"https://example.invalid/saved-response",number:17,title:"[reopen-candidate] consider re-opening #9",body:$body,state:"open"}'
    fi
  }
  failed=0
  check() { if ! "$@"; then printf 'FAIL: %s\n' "$*"; failed=$((failed+1)); fi; }
  rc=0; _filing_cross_link_enact probe > "$LOG_BASE/attempt.log" 2>&1 || rc=$?
  # The batch deliberately continues after a failed action; its saved success
  # must be quarantined and the uncertain POST must remain reserved.
  check test "$rc" -eq 0
  check test ! -e "$prefix.done"
  check test -f "$prefix.unverified-done"
  check test -f "$prefix.attempted"
  check test -f "$prefix.failed"
  check test -d "$target"
  check test -z "$(find -H "$target" -type f -print)"
  check test -z "$(find "$outside" -type f -print)"
  check test ! -e "$LOG_BASE/posts"
  if [[ "$action" == reopen-suggestion ]]; then
    check test "$(cat "$prefix.body.md")" = 'saved body'
  fi
  # A plain retry cannot repeat the saved POST after failed reattestation.
  rc=0; _filing_cross_link_enact probe > "$LOG_BASE/retry.log" 2>&1 || rc=$?
  check test "$rc" -eq 0
  check test ! -e "$prefix.done"
  check test ! -e "$LOG_BASE/posts"
  printf '%s/%s: %s failures\n' "$action" "$kind" "$failed"
  (( failed == 0 ))
)
failures=0
for action in comment reopen-suggestion; do
  for kind in directory symlink; do
    case_payload "$action" "$kind" || failures=$((failures+1))
  done
done
printf 'Cross-link payload object scenarios: %s failures\n' "$failures"
(( failures == 0 ))
