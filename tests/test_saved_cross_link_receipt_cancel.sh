# repolens-r5-p1-2: cancellation cannot revoke a saved cross-link receipt.
# shellcheck disable=SC2034,SC2329 # Production callbacks consume fixture globals.
set -uo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FIXTURE="$(mktemp -d)" || exit 1
trap 'rm -rf -- "$FIXTURE"' EXIT
case_saved_receipt() (
  # shellcheck source=/dev/null
  source "$REPO/lib/parallel.sh"
  # shellcheck source=/dev/null
  source "$REPO/lib/forge.sh"
  # shellcheck source=/dev/null
  source "$REPO/lib/filing.sh"
  phase="$1"
  LOG_BASE="$FIXTURE/$phase/run" PROJECT_PATH="$FIXTURE/$phase/project"
  FORGE_PROVIDER=gh FORGE_HOST=github.com FORGE_REPO=acme/probe
  MODE=bugreport CROSS_LINK_MODE=suggest-reopen RUN_ID=probe
  mkdir -p "$PROJECT_PATH/src" "$LOG_BASE/final/filed/cross-link"
  printf 'code\n' > "$PROJECT_PATH/src/a.sh"
  jq -n '[{cluster_id:"cluster",title:"parent",body:"src/a.sh:1",cross_link_actions:[{type:"reopen-suggestion",issue_number:9,body:"Please reconsider."}]}]' > "$LOG_BASE/final/manifest.json"
  cross="$LOG_BASE/final/filed/cross-link/reopen-suggestion-9"
  : > "$cross.done"
  printf 'https://github.com/acme/probe/issues/17\n' > "$cross.created-response"
  printf -v expected_banner '> Generated by RepoLens run probe\n> Source: closed issue #9\n\nPlease reconsider.\n\nLabel suggestion: %s\n' "\`repolens:reopen-candidate\`"
  printf '%s' "$expected_banner" > "$cross.body.banner.md"
  : > "$LOG_BASE/reads"
  parent_pid="$BASHPID"
  log_warn() { :; }
  parallel_preflight() { _REPOLENS_SCOPE_READY=1; }
  init_parallel "$LOG_BASE/.semaphore" 1
  cancel_enabled=false
  forge_filing_capable() { return 0; }
  forge_issue_read_json() {
    printf '%s\n' "$2" >> "$LOG_BASE/reads"
    if [[ "$2" == 9 ]]; then
      if $cancel_enabled && [[ "$phase" == target-* ]]; then
        kill -TERM "$parent_pid"
        [[ "$phase" != target-failure ]] || return 1
      fi
      if [[ "$phase" == invalid-target ]]; then printf '{"number":9,"state":"open"}\n';
      else printf '{"number":9,"state":"closed"}\n'; fi
    else
      jq -cn --rawfile body "$cross.body.banner.md" '{number:17,title:"[reopen-candidate] consider re-opening #9",body:$body,url:"https://github.com/acme/probe/issues/17",state:"open"}'
    fi
  }
  forge_issue_create_once() { printf 'UNEXPECTED POST\n' >> "$LOG_BASE/posts"; return 99; }
  cat() {
    command cat "$@" || return 1
    if $cancel_enabled && [[ "$phase" == banner-* && "${1:-}" == "$cross.body.md".reconcile.* ]]; then
      kill -TERM "$parent_pid"
      [[ "$phase" != banner-failure ]] || return 42
    fi
  }
  passed=0 failed=0
  check() { if "$@"; then passed=$((passed+1)); else failed=$((failed+1)); printf 'FAIL: %s: %s\n' "$phase" "$*"; fi; }
  REPOLENS_FINAL_STATE=finished
  count="$(filing_verified_issue_count probe)"
  check test "$?" -eq 0
  check test "$count" -eq 1
  : > "$LOG_BASE/reads"
  cancel_enabled=true
  enact_rc=0
  _filing_cross_link_enact probe || enact_rc=$?
  if [[ "$phase" == invalid-target ]]; then
    # Confirmed validation failures retain the existing quarantine/no-repost rule.
    check test "$enact_rc" -eq 0
    check test ! -e "$cross.done"
    check test -f "$cross.unverified-done"
    check test -f "$cross.attempted"
    check test -f "$cross.failed"
    check test "$(filing_verified_issue_count probe)" -eq 0
    _filing_cross_link_enact probe
    check test "$?" -eq 0
    check test ! -e "$LOG_BASE/posts"
    printf '%s: %s passed, %s failed\n' "$phase" "$passed" "$failed"
    (( failed == 0 ))
    exit "$?"
  fi
  if [[ "$phase" == control ]]; then
    check test "$enact_rc" -eq 0
  else
    check test "$enact_rc" -eq 1
    check test "$REPOLENS_FINAL_STATE" = interrupted
    check test "$(grep -c '^17$' "$LOG_BASE/reads" || true)" -eq 0
  fi
  check test -f "$cross.done"
  check test ! -e "$cross.unverified-done"
  check cmp -s <(printf '%s' "$expected_banner") "$cross.body.banner.md"
  # A fresh attempt counts the old receipt before and after enactor resume.
  REPOLENS_FINAL_STATE=finished cancel_enabled=false
  check test "$(filing_verified_issue_count probe)" -eq 1
  _filing_cross_link_enact probe
  check test "$?" -eq 0
  check test "$(filing_verified_issue_count probe)" -eq 1
  check test -f "$cross.done"
  check test ! -e "$cross.unverified-done"
  check test ! -e "$LOG_BASE/posts"
  printf '%s: %s passed, %s failed\n' "$phase" "$passed" "$failed"
  (( failed == 0 ))
)
failed_cases=0
for phase in control invalid-target target-success target-failure banner-success banner-failure; do
  case_saved_receipt "$phase" || failed_cases=$((failed_cases+1))
done
printf 'Saved-receipt scenarios: %s failed\n' "$failed_cases"
(( failed_cases == 0 ))
